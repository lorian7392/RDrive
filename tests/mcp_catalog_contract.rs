//! Every shipped MCP field must validate and map to a real CLI argument.
//! The production catalog is included directly; no second tool list is kept.
use rdrive::{backend, filtering};
use serde_json::{json, Map, Value};
use std::{
    collections::{BTreeMap, BTreeSet},
    path::Path,
    process::{Command, Stdio},
    sync::atomic::{AtomicUsize, Ordering},
};

#[path = "../src/mcp/catalog.rs"]
mod catalog;
use catalog::{Field, Kind, Tool};

struct Positive {
    label: String,
    argv: Vec<String>,
}

fn values(tool: &Tool, field: &Field, local: &Path) -> Vec<Value> {
    match field.kind {
        Kind::Bool => vec![json!(true), json!(false)],
        Kind::Direction => vec![json!("push"), json!("pull"), json!("both")],
        Kind::CheckpointStorage => vec![json!("system-snapshot"), json!("apfs-vault")],
        Kind::Patterns => vec![
            json!(["**/*.txt", "reports/**"]),
            json!([]),
            json!(vec!["*.txt"; 256]),
            json!(["x".repeat(4096)]),
        ],
        Kind::Number => match field.name {
            "max_items" => vec![json!(1),json!(10),json!(100)],
            "timeout" if tool.name=="rdrive_status_check_connections" => vec![json!(1),json!(10),json!(120)],
            "max_bytes" if tool.name=="rdrive_checkpoint_config" => vec![json!(268435456_u64),json!(21474836480_u64),json!(9007199254740480_u64)],
            "max_records" => vec![json!(1),json!(48),json!(4096)],
            "interval_secs" => vec![json!(60),json!(3600),json!(31_536_000)],
            "depth" => vec![json!(0), json!(1), json!(u32::MAX)],
            "refresh_seconds" | "active_refresh_seconds" => vec![json!(1), json!(31_536_000)],
            "page_size" => vec![json!(1), json!(1000)],
            "max_age_days" => vec![json!(1), json!(30), json!(36500)],
            _ => vec![json!(0), json!(1), json!(9_007_199_254_740_991_u64)],
        },
        Kind::Remote => vec![
            json!(format!("folder with space/{}-用户.txt", field.name)),
            json!(""),
        ],
        Kind::Local => vec![json!(local
            .join(format!("{} with space 用户", field.name))
            .to_str()
            .unwrap())],
        Kind::String => match field.name {
            "strategy" if tool.name == "rdrive_smart_resolve" => {
                vec![json!("keep-both"), json!("replace"), json!("remote")]
            }
            "conflicts" => vec![json!("stop"), json!("keep-both"), json!("replace")],
            "kind" => vec![json!("file"), json!("directory")],
            "profile" => vec![json!("contract-profile_1")],
            _ => vec![json!(format!("contract-{} 用户 with space", field.name))],
        },
    }
}

fn baseline(tool: &Tool, local: &Path) -> Value {
    let mut args = Map::new();
    for field in &tool.fields {
        if field.required {
            args.insert(field.name.into(), values(tool, field, local).remove(0));
        }
    }
    match tool.name {
        "rdrive_cache_config" => {
            args.insert("max_bytes".into(), json!(1));
        }
        "rdrive_cache_set_directory" => {
            args.insert(
                "directory".into(),
                json!(local.join("cache").to_str().unwrap()),
            );
        }
        _ => {}
    }
    Value::Object(args)
}

fn with_field(tool: &Tool, baseline: &Value, field: &Field, value: Value) -> Value {
    let mut args = baseline.clone();
    if tool.name == "rdrive_cache_config" && field.name == "unlimited" && value == true {
        args.as_object_mut().unwrap().remove("max_bytes");
    }
    if tool.name == "rdrive_cache_set_directory" && field.name == "default" && value == true {
        args.as_object_mut().unwrap().remove("directory");
    }
    args[field.name] = value;
    args
}

/// Check positions and option/value associations independently of their
/// interleaving, including repeated arrays and switches generated by [] lists.
fn assert_mapping(tool: &Tool, args: &Value, argv: &[String], label: &str) {
    assert!(
        argv.starts_with(
            &tool
                .command
                .iter()
                .map(|s| (*s).to_owned())
                .collect::<Vec<_>>()
        ),
        "{label}: command prefix"
    );
    assert!(
        argv.ends_with(
            &tool
                .fixed
                .iter()
                .map(|s| (*s).to_owned())
                .collect::<Vec<_>>()
        ),
        "{label}: fixed safety arguments"
    );
    let middle = &argv[tool.command.len()..argv.len() - tool.fixed.len()];
    let mut expected_positions = Vec::new();
    let mut expected_options: BTreeMap<String, Vec<Option<String>>> = BTreeMap::new();
    let mut option_arity = BTreeMap::new();
    for field in &tool.fields {
        if let Some(flag) = field.flag {
            option_arity.insert(flag.to_owned(), !matches!(field.kind, Kind::Bool));
            if matches!(field.kind, Kind::Patterns) {
                option_arity.insert(format!("--clear-{}", field.name), false);
            }
            let Some(value) = args.get(field.name) else {
                continue;
            };
            match field.kind {
                Kind::Bool => {
                    if value == true {
                        expected_options.entry(flag.into()).or_default().push(None);
                    }
                }
                Kind::Patterns => {
                    let patterns = value.as_array().unwrap();
                    if patterns.is_empty() {
                        expected_options
                            .entry(format!("--clear-{}", field.name))
                            .or_default()
                            .push(None);
                    } else {
                        expected_options.entry(flag.into()).or_default().extend(
                            patterns
                                .iter()
                                .map(|v| Some(v.as_str().unwrap().to_owned())),
                        );
                    }
                }
                _ => expected_options.entry(flag.into()).or_default().push(Some(
                    value
                        .as_str()
                        .map(str::to_owned)
                        .unwrap_or_else(|| value.to_string()),
                )),
            }
        } else if let Some(value) = args
            .get(field.name)
            .and_then(Value::as_str)
            .or(field.default)
        {
            expected_positions.push(value.to_owned());
        }
    }
    let mut actual_positions = Vec::new();
    let mut actual_options: BTreeMap<String, Vec<Option<String>>> = BTreeMap::new();
    let mut index = 0;
    while index < middle.len() {
        let word = &middle[index];
        if word.starts_with('-') {
            let consumes_value = *option_arity
                .get(word)
                .unwrap_or_else(|| panic!("{label}: unknown emitted flag {word}"));
            let value = if consumes_value {
                index += 1;
                Some(
                    middle
                        .get(index)
                        .unwrap_or_else(|| panic!("{label}: missing value for {word}"))
                        .clone(),
                )
            } else {
                None
            };
            actual_options.entry(word.clone()).or_default().push(value);
        } else {
            actual_positions.push(word.clone());
        }
        index += 1;
    }
    assert_eq!(
        actual_positions, expected_positions,
        "{label}: positional field order/defaults"
    );
    assert_eq!(
        actual_options, expected_options,
        "{label}: field flags, values, repetition and false switches"
    );
}

fn positive(tool: &Tool, args: Value, label: String, cases: &mut Vec<Positive>) {
    tool.validate(&args)
        .unwrap_or_else(|e| panic!("{label}: valid arguments rejected: {args}: {e:#}"));
    let argv = tool.argv(&args);
    assert_mapping(tool, &args, &argv, &label);
    cases.push(Positive { label, argv });
}

fn negative(tool: &Tool, args: Value, label: &str, count: &mut usize) {
    assert!(
        tool.validate(&args).is_err(),
        "{} {label}: invalid arguments accepted: {args}",
        tool.name
    );
    *count += 1;
}

fn bad_values(field: &Field) -> Vec<Value> {
    match field.kind {
        Kind::Bool => vec![Value::Null, json!("true"), json!(0), json!([]), json!({})],
        Kind::Number => vec![
            Value::Null,
            json!("1"),
            json!(true),
            json!(-1),
            json!(1.5),
            json!(9_007_199_254_740_992_u64),
        ],
        Kind::Patterns => vec![
            Value::Null,
            json!("*.txt"),
            json!({}),
            json!([1]),
            json!([""]),
            json!(["-flag"]),
            json!(["/absolute"]),
            json!(["../escape"]),
            json!(["a\\b"]),
            json!(["a\0b"]),
            json!(["["]),
            json!(vec!["*.txt"; 257]),
            json!(["x".repeat(4097)]),
        ],
        _ => {
            let mut bad = vec![
                Value::Null,
                json!(1),
                json!(true),
                json!([]),
                json!({}),
                json!("-flag"),
                json!("a\0b"),
                json!("a\nb"),
                json!("x".repeat(16 * 1024 + 1)),
            ];
            if !matches!(field.kind, Kind::Remote) {
                bad.push(json!(""));
            }
            if matches!(field.kind, Kind::Remote) {
                bad.extend([
                    json!("../escape"),
                    json!("a/../../escape"),
                    json!("/absolute"),
                    json!("a\\b"),
                ]);
            }
            if matches!(field.kind, Kind::Direction) {
                bad.push(json!("sideways"));
            }
            if matches!(field.kind, Kind::CheckpointStorage) {
                bad.push(json!("unsupported-storage"));
            }
            if field.name == "profile" {
                bad.extend([json!("invalid/profile"), json!("space name"), json!("用户")]);
            }
            if ["strategy", "conflicts", "kind"].contains(&field.name) {
                bad.push(json!("unsupported-choice"));
            }
            bad
        }
    }
}

fn assert_schema(tool: &Tool) {
    let schema = tool.schema();
    assert_eq!(schema["name"], tool.name);
    assert!(!tool.description.is_empty());
    assert_eq!(schema["annotations"]["readOnlyHint"], !tool.write);
    assert_eq!(schema["annotations"]["destructiveHint"], tool.write);
    assert_eq!(schema["inputSchema"]["additionalProperties"], false);
    let properties = schema["inputSchema"]["properties"].as_object().unwrap();
    assert_eq!(properties.len(), tool.fields.len());
    let required = schema["inputSchema"]["required"].as_array().unwrap();
    for field in &tool.fields {
        assert_eq!(
            required.contains(&json!(field.name)),
            field.required,
            "{} {} required",
            tool.name,
            field.name
        );
        let expected_type = match field.kind {
            Kind::Bool => "boolean",
            Kind::Number => "integer",
            Kind::Patterns => "array",
            _ => "string",
        };
        assert_eq!(properties[field.name]["type"], expected_type);
    }
}

#[test]
fn all_mcp_tools_and_fields_validate_map_and_parse_without_executing() {
    let temporary = tempfile::tempdir().unwrap();
    let home = temporary.path().join("never-created-rdrive-home");
    let local = temporary.path().join("never-created-local-files");
    let tools = catalog::catalog();
    let mut names = BTreeSet::new();
    let mut mapped_fields = BTreeSet::new();
    let mut cases = Vec::new();
    let mut rejected = 0;
    for tool in &tools {
        assert!(names.insert(tool.name), "duplicate tool {}", tool.name);
        assert_schema(tool);
        let baseline = baseline(tool, &local);
        positive(
            tool,
            baseline.clone(),
            format!("{} baseline", tool.name),
            &mut cases,
        );
        for field in &tool.fields {
            assert!(
                mapped_fields.insert((tool.name, field.name)),
                "duplicate field {} {}",
                tool.name,
                field.name
            );
            for (index, value) in values(tool, field, &local).into_iter().enumerate() {
                positive(
                    tool,
                    with_field(tool, &baseline, field, value),
                    format!("{} {} value {index}", tool.name, field.name),
                    &mut cases,
                );
            }
            for value in bad_values(field) {
                negative(
                    tool,
                    with_field(tool, &baseline, field, value),
                    field.name,
                    &mut rejected,
                );
            }
            if field.required {
                let mut missing = baseline.clone();
                missing.as_object_mut().unwrap().remove(field.name);
                negative(tool, missing, "missing required field", &mut rejected);
            }
        }
        let mut unknown = baseline.clone();
        unknown["unexpected_contract_field"] = json!(true);
        negative(tool, unknown, "unknown field", &mut rejected);
        for shape in [
            Value::Null,
            json!([]),
            json!("string"),
            json!(true),
            json!(1),
        ] {
            negative(tool, shape, "not an object", &mut rejected);
        }
    }
    let tool = |name: &str| tools.iter().find(|tool| tool.name == name).unwrap();
    for (name, invalid) in [
        ("rdrive_checkpoint_config", json!({"manual":true,"interval_secs":3600})),
        ("rdrive_checkpoint_config", json!({"interval_secs":59})),
        ("rdrive_checkpoint_config", json!({"interval_secs":31536001})),
        ("rdrive_checkpoint_config", json!({"max_records":0})),
        ("rdrive_checkpoint_config", json!({"max_records":4097})),
        ("rdrive_checkpoint_config", json!({"max_bytes":268435455})),
        ("rdrive_checkpoint_config", json!({"max_bytes":268435457})),
        ("rdrive_cache_config", json!({})),
        ("rdrive_cache_config", json!({"unlimited":false})),
        (
            "rdrive_cache_config",
            json!({"max_bytes":1,"unlimited":true}),
        ),
        ("rdrive_cache_set_directory", json!({})),
        ("rdrive_cache_set_directory", json!({"default":false})),
        (
            "rdrive_cache_set_directory",
            json!({"directory":local.to_str().unwrap(),"default":true}),
        ),
        ("rdrive_index_config", json!({"enable":true,"disable":true})),
        ("rdrive_index_config", json!({"depth":0,"all":true})),
        (
            "rdrive_index_config",
            json!({"depth":u64::from(u32::MAX)+1}),
        ),
        ("rdrive_index_config", json!({"refresh_seconds":0})),
        ("rdrive_index_config", json!({"refresh_seconds":31_536_001})),
        ("rdrive_index_config", json!({"active_refresh_seconds":0})),
        (
            "rdrive_index_config",
            json!({"active_refresh_seconds":31_536_001}),
        ),
        (
            "rdrive_filter_config",
            json!({"exclude_temporary":true,"include_temporary":true}),
        ),
        (
            "rdrive_filter_config",
            json!({"clear_include":true,"include":["*.txt"]}),
        ),
        (
            "rdrive_filter_config",
            json!({"clear_exclude":true,"exclude":[]}),
        ),
        (
            "rdrive_policy_config",
            json!({"enable_versions":true,"disable_versions":true}),
        ),
        (
            "rdrive_policy_config",
            json!({"clear_include":true,"include":[]}),
        ),
        (
            "rdrive_policy_config",
            json!({"clear_exclude":true,"exclude":["*.tmp"]}),
        ),
        ("rdrive_status", json!({"max_items":0})),
        ("rdrive_status", json!({"max_items":101})),
        ("rdrive_status_check_connections", json!({"timeout":0})),
        ("rdrive_status_check_connections", json!({"timeout":121})),
        ("rdrive_smart_pause", json!({"all":true})),
        ("rdrive_smart_resume", json!({"domain":"unexpected-domain"})),
    ] {
        negative(tool(name), invalid, "cross-field contract", &mut rejected);
    }
    for page_size in [0, 1001] {
        let selected = tool("rdrive_index_search");
        let mut args = baseline(selected, &local);
        args["page_size"] = json!(page_size);
        negative(selected, args, "pagination bound", &mut rejected);
    }
    assert_eq!(
        mapped_fields.len(),
        tools.iter().map(|t| t.fields.len()).sum::<usize>()
    );
    // Only Clap help is run: even service, mount and remote write mappings
    // must leave both the temporary state and local payload paths nonexistent.
    let next = AtomicUsize::new(0);
    std::thread::scope(|scope| {
        for _ in 0..8 {
            scope.spawn(|| loop {
                let index = next.fetch_add(1, Ordering::Relaxed);
                let Some(case) = cases.get(index) else { break };
                let output = Command::new(env!("CARGO_BIN_EXE_rdrive"))
                    .args(&case.argv)
                    .arg("--help")
                    .env("RDRIVE_HOME", &home)
                    .stdin(Stdio::null())
                    .output()
                    .unwrap();
                assert!(
                    output.status.success(),
                    "{}: CLI rejected {:?}: {}",
                    case.label,
                    case.argv,
                    String::from_utf8_lossy(&output.stderr)
                );
                assert!(
                    String::from_utf8_lossy(&output.stdout).contains("Usage:"),
                    "{}: expected help, not execution",
                    case.label
                );
                assert!(!home.exists(), "{}: help created state", case.label);
                assert!(
                    !local.exists(),
                    "{}: help touched a local payload",
                    case.label
                );
            });
        }
    });
    eprintln!(
        "MCP_CONTRACT tools={} fields={} positive={} negative={} cli_help={} state_created=false",
        tools.len(),
        mapped_fields.len(),
        cases.len(),
        rejected,
        cases.len()
    );
}
